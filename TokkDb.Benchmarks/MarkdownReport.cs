using System.Diagnostics;
using System.Globalization;
using System.Runtime.InteropServices;
using System.Text;

namespace TokkDb.Benchmarks;

//Writes docs/benchmarks.md. Runs accumulate newest first, because the experimental chapter
//needs to show how the numbers moved from phase to phase, not only where they ended up.
public static class MarkdownReport {
  private const string RunsMarker = "<!-- runs -->";

  public static string Write(string filePath, string phase, BenchmarkContext context,
      IReadOnlyList<IBenchmark> benchmarks, IReadOnlyList<Measurement> measurements) {
    var previousRuns = ReadPreviousRuns(filePath);
    var builder = new StringBuilder();
    builder.AppendLine("# TokkDb benchmarks");
    builder.AppendLine();
    builder.AppendLine("Generated by `TokkDb.Benchmarks`. To reproduce:");
    builder.AppendLine();
    builder.AppendLine("```bash");
    builder.AppendLine("dotnet run -c Release --project TokkDb.Benchmarks -- --records 5000 --collections 500");
    builder.AppendLine("```");
    builder.AppendLine();
    builder.AppendLine("`--records 100000` runs the record count NFR-2 states its targets against; it takes");
    builder.AppendLine("appreciably longer, because every insert is its own transaction.");
    builder.AppendLine();
    builder.AppendLine("Each run is appended below, newest first.");
    builder.AppendLine();
    builder.AppendLine(RunsMarker);
    builder.AppendLine();
    AppendRun(builder, phase, context, benchmarks, measurements);
    builder.Append(previousRuns);

    Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(filePath))!);
    File.WriteAllText(filePath, builder.ToString());
    return filePath;
  }

  private static void AppendRun(StringBuilder builder, string phase, BenchmarkContext context,
      IReadOnlyList<IBenchmark> benchmarks, IReadOnlyList<Measurement> measurements) {
    builder.AppendLine($"## {DateTime.Now:yyyy-MM-dd} — {phase}");
    builder.AppendLine();
    builder.AppendLine("| | |");
    builder.AppendLine("|---|---|");
    builder.AppendLine(CultureInfo.InvariantCulture, $"| Records | {context.RecordCount:N0} |");
    builder.AppendLine(CultureInfo.InvariantCulture, $"| Collections | {context.CollectionCount:N0} |");
    builder.AppendLine($"| Runtime | {RuntimeInformation.FrameworkDescription} |");
    builder.AppendLine($"| OS | {RuntimeInformation.OSDescription.Trim()} ({RuntimeInformation.OSArchitecture}) |");
    builder.AppendLine($"| Processors | {Environment.ProcessorCount} |");
    builder.AppendLine($"| Commit | {_commit ?? ReadGitCommit()} |");
    builder.AppendLine();
    builder.AppendLine("| Benchmark | Metric | Measured | Target | Requirement | Verdict |");
    builder.AppendLine("|---|---|---|---|---|---|");
    foreach (var measurement in measurements) {
      builder.AppendLine($"| {measurement.Benchmark} | {measurement.Metric} | " +
        $"{measurement.FormatValue()} {measurement.Unit} | {measurement.FormatTarget()} | " +
        $"{(measurement.Requirement.Length == 0 ? "—" : measurement.Requirement)} | " +
        $"{measurement.FormatVerdict()} |");
    }
    builder.AppendLine();
    builder.AppendLine("### Notes");
    builder.AppendLine();
    foreach (var benchmark in benchmarks) {
      builder.AppendLine($"- **{benchmark.Name}** — {benchmark.Description}");
    }
    foreach (var measurement in measurements.Where(measurement => measurement.Note.Length > 0)) {
      builder.AppendLine($"- *{measurement.Metric}:* {measurement.Note}");
    }
    builder.AppendLine();
  }

  private static string ReadPreviousRuns(string filePath) {
    if (!File.Exists(filePath)) {
      return string.Empty;
    }
    var existing = File.ReadAllText(filePath);
    var index = existing.IndexOf(RunsMarker, StringComparison.Ordinal);
    return index < 0 ? string.Empty : existing[(index + RunsMarker.Length)..].TrimStart('\r', '\n');
  }

  //Read once, before the run starts. A run at NFR-2 scale takes over an hour, and the
  //repository can move on in that time: stamping the commit at write time would attribute
  //the numbers to code that did not produce them.
  private static string? _commit;

  public static void CaptureCommit() {
    _commit = ReadGitCommit();
  }

  private static string ReadGitCommit() {
    try {
      using var process = Process.Start(new ProcessStartInfo("git", "rev-parse --short HEAD") {
        RedirectStandardOutput = true,
        RedirectStandardError = true
      });
      if (process is null) {
        return "unknown";
      }
      var commit = process.StandardOutput.ReadToEnd().Trim();
      process.WaitForExit(5000);
      return commit.Length == 0 ? "unknown" : commit;
    } catch {
      return "unknown";
    }
  }

  public static void WriteConsole(IReadOnlyList<Measurement> measurements) {
    foreach (var measurement in measurements) {
      Console.WriteLine(string.Format(CultureInfo.InvariantCulture, "{0,-22} {1,-34} {2,14} {3,-12} {4}",
        measurement.Benchmark, measurement.Metric, measurement.FormatValue(), measurement.Unit,
        measurement.FormatVerdict()));
    }
  }
}
